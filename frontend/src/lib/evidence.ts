import type { ClaimType, ConfidenceLabel, EvidenceType } from "@/lib/api/types";

export type EvidenceUiLabel =
  | "Observed outcome"
  | "Synthetic"
  | "Calculated"
  | "Unverified"
  | "Model interpretation"
  | "Source data";

/** UI label for an evidence record (contracts/README §7). Rows are checked in order; the first match wins. */
export function evidenceLabel(e: { evidence_type: EvidenceType; claim_type: ClaimType }): EvidenceUiLabel {
  if (e.evidence_type === "observed_outcome") return "Observed outcome";
  if (e.evidence_type === "synthetic_response" || e.claim_type === "synthetic") return "Synthetic";
  if (e.evidence_type === "deterministic_calculation") return "Calculated";
  if (e.claim_type === "hypothesis") return "Unverified";
  if (e.evidence_type === "model_interpretation") return "Model interpretation";
  // Remaining evidence types: qloo_source, provider_result, user_input.
  return "Source data";
}

/** Claim type → UI label, for findings that carry a claim type but no evidence type. */
export const CLAIM_LABEL: Record<ClaimType, EvidenceUiLabel> = {
  observed: "Source data",
  derived: "Calculated",
  interpreted: "Model interpretation",
  hypothesis: "Unverified",
  synthetic: "Synthetic",
  external_observation: "Observed outcome",
};

