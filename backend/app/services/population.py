# --- converters ------------------------------------------------------------------------------------------------


def to_population(row: m.Population) -> ps.Population:
    return ps.Population(
        id=row.id, project_id=row.project_id, study_id=row.study_id, size=row.size, regions=row.regions,
        group_count=len(row.groups), mode=row.mode, created_at=row.created_at, groups=row.groups,  # type: ignore[arg-type]
        construction=row.construction, limitations=row.limitations,  # type: ignore[arg-type]
    )


def to_participant(row: m.Participant) -> ps.Participant:
    return ps.Participant(
        id=row.id, population_id=row.population_id, group_id=row.group_id, ordinal=row.ordinal, region=row.region,
        interests=row.interests, traits=row.traits, evidence_ids=row.evidence_ids,  # type: ignore[arg-type]
    )


def to_interview(row: m.Interview) -> ps.Interview:
    return ps.Interview.model_validate(row.payload)


def to_post(row: m.SocialPost) -> ps.SocialPost:
    return ps.SocialPost(
        id=row.id, round_index=row.round_index, participant_id=row.participant_id, group_id=row.group_id,
        action=row.action, parent_post_id=row.parent_post_id, text=row.text, stance=row.stance,  # type: ignore[arg-type]
        previous_stance=row.previous_stance, reason=row.reason, seen_post_ids=row.seen_post_ids,  # type: ignore[arg-type]
    )


async def _interviews(s: AsyncSession, study_id: UUID, *where: Any) -> list[ps.Interview]:
    stmt = select(m.Interview).where(m.Interview.run_id == study_id, *where).order_by(m.Interview.batch_index, m.Interview.id)
    return [to_interview(r) for r in (await s.execute(stmt)).scalars()]


async def _participants(s: AsyncSession, population_id: UUID) -> list[ps.Participant]:
    stmt = select(m.Participant).where(m.Participant.population_id == population_id).order_by(m.Participant.ordinal)
    return [to_participant(r) for r in (await s.execute(stmt)).scalars()]


async def _posts(s: AsyncSession, simulation_id: UUID, *where: Any) -> list[ps.SocialPost]:
    stmt = select(m.SocialPost).where(m.SocialPost.simulation_id == simulation_id, *where).order_by(
        m.SocialPost.round_index, m.SocialPost.created_at, m.SocialPost.id)
    return [to_post(r) for r in (await s.execute(stmt)).scalars()]


# --- population studies: start -------------------------------------------------------------------------------


def _too_large(size: int, limit: int) -> ValidationFailed:
    message = f"A population study can interview at most {limit} participants per run; requested {size}."
    return ValidationFailed(message, details=[ErrorDetail(field="population_size", message=message)])


async def start_population_study(user_id: UUID, study_id: UUID, body: ps.PopulationStudyCreate) -> RunAccepted:
    async with read_session() as s:
        study, project = await get_owned(s, m.Study, study_id, user_id, "Study")
        require_writable(project)
        campaign = await s.get(m.Campaign, study.campaign_id)
        assert campaign is not None
        population: m.Population | None = None
        if body.population_id is not None:
            population, _ = await get_owned(s, m.Population, body.population_id, user_id, "Population", "population_id")
            owner_study = await s.get(m.Study, population.study_id)
            if population.project_id != project.id or owner_study is None or owner_study.campaign_id != campaign.id:
                raise conflict("population_id", "The population belongs to another campaign.")
            size, regions = population.size, population.regions
        else:
            if body.population_size is None:
                message = "population_size is required when population_id is not given."
                raise ValidationFailed(message, details=[ErrorDetail(field="population_size", message=message)])
            size = body.population_size
            regions = [r.model_dump(mode="json") for r in body.regions] or [study.market]
        if project.mode == "demo" and size > DEMO_CAP:
            raise Conflict(f"Demo projects simulate at most {DEMO_CAP} participants (the fixtures describe no more). "
                           "Create a live project for larger populations.")
        if size > (limit := get_settings().population_max_participants):
            raise _too_large(size, limit)
        for index, region in enumerate(regions):
            _check_demo_market(project, region["country_code"], f"regions.{index}.country_code")
        version = await _version_of(s, user_id, body.content_version_id, campaign, "content_version_id")
        evidence_run = None
        if body.discovery_run_id is not None:
            evidence_run = await usable_run(s, user_id, body.discovery_run_id, "market_discovery", project.id, "discovery_run_id")
        else:  # the campaign's latest linked discovery
            evidence_run = (await s.execute(
                select(m.AgentRun).where(m.AgentRun.project_id == project.id, m.AgentRun.campaign_id == campaign.id,
                                         m.AgentRun.run_type == "market_discovery", m.AgentRun.status.in_(USABLE))
                .order_by(m.AgentRun.created_at.desc()).limit(1))).scalar_one_or_none()
        grounding = await _grounding_ids(s, evidence_run) if evidence_run else []
        if body.asset_id is not None:
            asset, _ = await get_owned(s, m.Asset, body.asset_id, user_id, "Asset", "asset_id")
            if asset.project_id != project.id or asset.kind != "image":
                raise conflict("asset_id", "The asset must be an image in this project.")
    inputs = {"request": body.model_dump(mode="json"), "size": size, "regions": regions,
              "content_version_id": str(version.id), "evidence_run_id": str(evidence_run.id) if evidence_run else None,
              "grounding_evidence_ids": grounding, "batch_size": BATCH_SIZE}

    def rows(run: m.AgentRun) -> list[Any]:
        return [m.PopulationStudy(
            id=run.id, project_id=project.id, study_id=study.id, campaign_id=campaign.id,
            population_id=population.id if population else None, content_version_id=version.id,
            requested_participants=size, interview_depth=body.interview_depth, seed=body.seed if body.seed is not None else 42,
            checkpoint={"completed_batches": [], "batch_size": BATCH_SIZE}, result=None,
            created_at=run.created_at, updated_at=run.created_at,
        )]

    return await _create_run(user_id, project, "population_study", inputs, campaign_id=campaign.id, extra_rows=rows)


# --- population studies: reads -------------------------------------------------------------------------------


async def _study_summary(s: AsyncSession, row: m.PopulationStudy) -> dict[str, Any]:
    run = await s.get(m.AgentRun, row.id)
    assert run is not None
    counts = dict((await s.execute(select(m.Interview.status, func.count()).where(m.Interview.run_id == row.id)
                                   .group_by(m.Interview.status))).all())
    return {"id": row.id, "project_id": row.project_id, "study_id": row.study_id, "campaign_id": row.campaign_id,
            "population_id": row.population_id or row.id, "content_version_id": row.content_version_id,
            "status": run.status, "mode": run.mode, "requested_participants": row.requested_participants,
            "completed_interviews": counts.get("completed", 0), "failed_interviews": counts.get("failed", 0),
            "created_at": row.created_at, "_run": run}


async def list_population_studies(user_id: UUID, study_id: UUID, limit: int, offset: int) -> ps.PopulationStudyPage:
    async with read_session() as s:
        await get_owned(s, m.Study, study_id, user_id, "Study")
        stmt = select(m.PopulationStudy).where(m.PopulationStudy.study_id == study_id)
        rows, total = await paginate(s, stmt.order_by(m.PopulationStudy.created_at.desc(), m.PopulationStudy.id), limit, offset)
        items = []
        for row in rows:
            summary = await _study_summary(s, row)
            summary.pop("_run")
            items.append(ps.PopulationStudySummary.model_validate(summary))
    return ps.PopulationStudyPage(items=items, limit=limit, offset=offset, total=total)


async def _owned_study(s: AsyncSession, user_id: UUID, population_study_id: UUID) -> tuple[m.PopulationStudy, m.Project]:
    return await get_owned(s, m.PopulationStudy, population_study_id, user_id, "Population study")


async def get_population_study(user_id: UUID, population_study_id: UUID) -> ps.PopulationStudyResult:
    async with read_session() as s:
        row, _ = await _owned_study(s, user_id, population_study_id)
        summary = await _study_summary(s, row)
        run = summary.pop("_run")
        interviews = await _interviews(s, row.id)
        population = await s.get(m.Population, row.population_id) if row.population_id else None
        groups = [ps.PopulationGroup.model_validate(g) for g in population.groups] if population else []
        stored = row.result or {}
        evidence = await evidence_by_ids(s, row.project_id, stored.get("evidence_ids", []))
    completed = [i for i in interviews if i.status == "completed"]
    return ps.PopulationStudyResult.model_validate(summary | {
        "overall": _pa().distribution(interviews),
        "by_group": _pa().group_results(groups, interviews),
        "by_region": _pa().region_results([Market.model_validate(r) for r in (population.regions if population else [])],
                                          interviews),
        "themes": _pa().theme_counts(completed, "themes"),
        "misunderstandings": _pa().theme_counts(completed, "misunderstanding"),
        "concerns": _pa().theme_counts(completed, "concerns"),
        "group_differences": stored.get("group_differences", []), "evidence_gaps": stored.get("evidence_gaps", []),
        "next_actions": stored.get("next_actions", []), "disclosure": DISCLOSURE, "evidence": evidence,
        "limitations": stored.get("limitations", [] if row.result else ["The study has not finished, or it stopped early; "
                                                                         "tallies cover the stored interviews only."]),
        "run_metadata": run_metadata(run),
    })


async def list_interviews(user_id: UUID, population_study_id: UUID, group_id: str | None, region: str | None,
                          reaction: str | None, limit: int, offset: int) -> ps.InterviewPage:
    async with read_session() as s:
        row, _ = await _owned_study(s, user_id, population_study_id)
        stmt = select(m.Interview).where(m.Interview.run_id == row.id)
        for column, value in (("group_id", group_id), ("region_code", region), ("reaction", reaction)):
            if value is not None:
                stmt = stmt.where(getattr(m.Interview, column) == value)
        rows, total = await paginate(s, stmt.order_by(m.Interview.batch_index, m.Interview.id), limit, offset)
    return ps.InterviewPage(items=[to_interview(r) for r in rows], limit=limit, offset=offset, total=total)


