async def ask_group(user_id: UUID, population_study_id: UUID, group_id: str, body: ps.GroupQuestionCreate) -> ps.GroupQuestionResult:
    async with read_session() as s:
        row, project = await _owned_study(s, user_id, population_study_id)
        require_writable(project)
        members = list((await s.execute(select(m.Participant).where(
            m.Participant.population_id == row.population_id, m.Participant.group_id == group_id)
            .order_by(m.Participant.ordinal))).scalars()) if row.population_id else []
    if not members:
        raise not_found("Group")
    answer_group_question = _answerer("answer_group_question")
    sample = sorted(random.Random(f"{row.seed}:{group_id}:{body.question}").sample(
        members, min(body.sample_size, len(members))), key=lambda p: p.ordinal)
    details = [await participant_detail(user_id, population_study_id, p.id) for p in sample]
    result = await _answer(answer_group_question, population_study_id=row.id, group_id=group_id, participants=details,
                           question=body.question, mode=project.mode)
    question_id, now = uuid4(), utcnow()
    by_id = {d.id: d for d in details}
    answers = list({a.participant_id: a for a in result.answers if a.participant_id in by_id}.values())  # sampled only
    note = (f"A seeded sample of {len(sample)} of the group's {len(members)} participants was asked; {len(answers)} "
            "answered. The tally covers those answers only.")
    stance = _pa().stance_distribution(a.stance for a in answers)
    rows = [m.FollowUp(id=uuid4(), project_id=project.id, population_study_id=row.id, participant_id=a.participant_id,
                       group_id=group_id, group_question_id=question_id, question=body.question, answer=a.answer,
                       stance=a.stance, memory_refs=_known_refs(a.memory_refs, by_id[a.participant_id]),
                       model_id=a.model_id, created_at=now)
            for a in answers]
    async with session() as s, s.begin():
        s.add(m.GroupQuestion(id=question_id, project_id=project.id, population_study_id=row.id, group_id=group_id,
                              question=body.question, sample_size=len(sample), stance=stance.model_dump(mode="json"),
                              summary=result.summary, sample_note=note, created_at=now))
        await s.flush()
        s.add_all(rows)
    return ps.GroupQuestionResult(id=question_id, population_study_id=row.id, group_id=group_id, question=body.question,
                                  answers=[_to_follow_up(r) for r in rows], stance=stance, summary=result.summary,
                                  sample_note=note, created_at=now)


