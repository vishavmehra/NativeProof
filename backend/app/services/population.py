async def build_input(s: AsyncSession, run: m.AgentRun, types: Any, context: Any, grounding: list[Any]) -> Any:
    if run.run_type == "population_study":
        row = await s.get(m.PopulationStudy, run.id)
        study = await s.get(m.Study, row.study_id)
        version = await s.get(m.CampaignVersion, row.content_version_id)
        assert row is not None and study is not None and version is not None
        population = await s.get(m.Population, row.population_id) if row.population_id else None
        done = sorted(row.checkpoint.get("completed_batches", []))
        request = run.inputs["request"]
        asset = None
        if request.get("asset_id"):
            stored = await s.get(m.Asset, UUID(request["asset_id"]))
            if stored is not None:
                asset = types.AssetBlob(asset_id=stored.id, media_type=stored.content_type, data=await stored_bytes(stored))
        evidence_run = run.inputs.get("evidence_run_id")
        discovery = await s.get(m.AgentRun, UUID(evidence_run)) if evidence_run else None
        concept = ((discovery.inputs or {}).get("request") or {}).get("product_category") if discovery else None
        return types.PopulationStudyInput(
            context=context, population_study_id=row.id, study=to_study(study, None),
            population=to_population(population) if population else None,
            participants=await _participants(s, population.id) if population else [],
            size=run.inputs["size"], regions=run.inputs["regions"], seed=row.seed, content_version_id=version.id,
            content=CampaignContent.model_validate(version.content), asset=asset, interview_depth=row.interview_depth,
            grounding_evidence=grounding, evidence_run_id=UUID(evidence_run) if evidence_run else None, concept=concept,
            batch_size=row.checkpoint.get("batch_size", BATCH_SIZE), completed_batches=done,
            completed_interviews=await _interviews(s, row.id) if done else [],
        )
    row = await s.get(m.SocialSimulation, run.id)
    assert row is not None
    study = await s.get(m.PopulationStudy, row.population_study_id)
    assert study is not None and study.population_id is not None
    population = await s.get(m.Population, study.population_id)
    version = await s.get(m.CampaignVersion, study.content_version_id)
    assert population is not None and version is not None
    return types.SocialSimulationInput(
        context=context, simulation_id=row.id, population_study_id=study.id,
        groups=[ps.PopulationGroup.model_validate(g) for g in population.groups],
        participants=await _participants(s, population.id), interviews=await _interviews(s, study.id),
        content=CampaignContent.model_validate(version.content), rounds=row.rounds_requested,
        active_share=row.active_share, feed_size=row.feed_size, seed=row.seed,
        completed_rounds=sorted(row.checkpoint.get("completed_rounds", [])), prior_posts=await _posts(s, row.id),
    )


def checkpoint_for(run_id: UUID, run_type: str) -> Any:
    """The callback the workflow awaits after each event. Idempotent by index; honors a pending cancel afterwards."""

    async def checkpoint(event: Any) -> None:
        name = type(event).__name__
        async with session() as s, s.begin():
            run = await s.get(m.AgentRun, run_id)
            assert run is not None
            if name == "PopulationBuilt":
                await _save_population(s, run, event)
            elif name == "InterviewBatch":
                await _save_batch(s, run, event)
            elif name == "SocialRound":
                await _save_round(s, run, event)
            cancel = run.cancel_requested_at is not None
        if cancel:
            raise RunCancelled()

    return checkpoint


async def _save_population(s: AsyncSession, run: m.AgentRun, event: Any) -> None:
    row = await s.get(m.PopulationStudy, run.id)
    assert row is not None
    if row.population_id is not None:
        return  # already built (resume)
    population = event.population
    if event.evidence:  # the Qloo records the groups cite, saved now so a resumed run never cites unsaved records
        ids = [e.id for e in event.evidence]
        stored = set((await s.execute(select(m.EvidenceRecord.id).where(m.EvidenceRecord.id.in_(ids)))).scalars())
        s.add_all(_evidence_row(run, e) for e in event.evidence if e.id not in stored)
    s.add(m.Population(id=population.id, project_id=run.project_id, study_id=row.study_id, size=population.size,
                       regions=[r.model_dump(mode="json") for r in population.regions],
                       groups=[g.model_dump(mode="json") for g in population.groups],
                       construction=population.construction.model_dump(mode="json"), limitations=population.limitations,
                       mode=run.mode, created_at=utcnow()))
    await s.flush()
    s.add_all(m.Participant(id=p.id, project_id=run.project_id, population_id=population.id, group_id=p.group_id,
                            ordinal=p.ordinal, region_code=p.region.country_code, region=p.region.model_dump(mode="json"),
                            interests=[i.model_dump(mode="json") for i in p.interests], traits=dict(p.traits),
                            evidence_ids=[str(x) for x in p.evidence_ids]) for p in event.participants)
    row.population_id, row.updated_at = population.id, utcnow()
    await s.flush()
    await _progress(s, run, "constructing_population", 1, f"Built {population.size} participants in "
                                                          f"{len(population.groups)} groups.")


async def _save_batch(s: AsyncSession, run: m.AgentRun, event: Any) -> None:
    row = await s.get(m.PopulationStudy, run.id)
    assert row is not None
    done = list(row.checkpoint.get("completed_batches", []))
    if event.index in done:
        return  # idempotent by batch index
    stored = set((await s.execute(select(m.Interview.participant_id).where(m.Interview.run_id == row.id))).scalars())
    for interview in event.interviews:
        if interview.participant_id in stored:
            continue
        s.add(m.Interview(id=interview.id, project_id=run.project_id, run_id=row.id, participant_id=interview.participant_id,
                          batch_index=event.index, group_id=interview.group_id, region_code=interview.region.country_code,
                          status=interview.status, reaction=interview.reaction,
                          payload=interview.model_dump(mode="json"), created_at=utcnow()))
    row.checkpoint = row.checkpoint | {"completed_batches": sorted(done + [event.index])}
    row.updated_at = utcnow()
    await s.flush()
    total = await s.scalar(select(func.count()).select_from(m.Interview).where(m.Interview.run_id == row.id)) or 0
    await _progress(s, run, "running_interviews", 2, f"Interviewed {total} of {row.requested_participants} participants.")


async def _save_round(s: AsyncSession, run: m.AgentRun, event: Any) -> None:
    row = await s.get(m.SocialSimulation, run.id)
    assert row is not None
    done = list(row.checkpoint.get("completed_rounds", []))
    if event.index in done:
        return  # idempotent by round index
    for post in event.posts:
        s.add(m.SocialPost(id=post.id, project_id=run.project_id, simulation_id=row.id, round_index=post.round_index,
                           participant_id=post.participant_id, group_id=post.group_id, action=post.action,
                           parent_post_id=post.parent_post_id, text=post.text, stance=post.stance,
                           previous_stance=post.previous_stance, reason=post.reason,
                           seen_post_ids=[str(x) for x in post.seen_post_ids], created_at=utcnow()))
    before = {UUID(k): v for k, v in row.checkpoint.get("stances", {}).items()}
    if not before:
        study_interviews = (await s.execute(select(m.Interview.participant_id, m.Interview.reaction)
                                            .where(m.Interview.run_id == row.population_study_id))).all()
        before = {pid: reaction for pid, reaction in study_interviews}
    summary = _pa().round_summary(event.index, event.posts, before, dict(event.stances))
    row.checkpoint = row.checkpoint | {
        "completed_rounds": sorted(done + [event.index]),
        "rounds": row.checkpoint.get("rounds", []) + [summary.model_dump(mode="json")],
        "stances": {str(k): v for k, v in event.stances.items()},
    }
    row.updated_at = utcnow()
    await s.flush()
    await _progress(s, run, "simulating_rounds", 1, f"Simulated round {event.index} of {row.rounds_requested}.")


async def _progress(s: AsyncSession, run: m.AgentRun, stage: str, completed: int, message: str) -> None:
    await s.execute(update(m.AgentRun).where(m.AgentRun.id == run.id, m.AgentRun.status == "running").values(
        progress={"stage": stage, "completed_steps": completed, "total_steps": 4, "message": message}))


async def persist(s: AsyncSession, run: m.AgentRun, outcome: Any, new_ids: list[str], now: Any) -> tuple[dict, tuple[str, list, str]]:
    if run.run_type == "population_study":
        row = await s.get(m.PopulationStudy, run.id)
        assert row is not None
        row.result = {"group_differences": list(outcome.group_differences), "evidence_gaps": list(outcome.evidence_gaps),
                      "next_actions": list(outcome.next_actions), "limitations": list(outcome.limitations),
                      # outcome.evidence was mostly saved with the population already, so it is not "new" here
                      "evidence_ids": _union_ids(run.inputs.get("grounding_evidence_ids", []), new_ids,
                                                 [e.id for e in outcome.evidence]),
                      "qloo_calls": [c.model_dump(mode="json") for c in getattr(outcome, "qloo_calls", [])]}
        row.updated_at = now
        return {"population_study_id": str(row.id)}, ("population_study", [row.id], f"{API}/population-studies/{row.id}")
    row = await s.get(m.SocialSimulation, run.id)
    assert row is not None
    row.result = {"network": outcome.network.model_dump(mode="json"), "influence_paths": list(outcome.influence_paths),
                  "limitations": list(outcome.limitations)}
    row.updated_at = now
    return {"simulation_id": str(row.id)}, ("social_simulation", [row.id], f"{API}/social-simulations/{row.id}")


def _union_ids(*groups: list[Any]) -> list[str]:
    return list(dict.fromkeys(str(i) for group in groups for i in group))


def result_ref(run: m.AgentRun) -> dict[str, Any]:
    """Where a population or social run's saved work lives (also for cancelled and failed runs)."""
    resource, path = ("population_study", "population-studies") if run.run_type == "population_study" else (
        "social_simulation", "social-simulations")
    return {"resource": resource, "ids": [str(run.id)], "url": f"{API}/{path}/{run.id}"}

