async def landscape(user_id: UUID, population_id: UUID, region: str | None, interest: str | None, limit: int) -> ps.GraphView:
    async with read_session() as s:
        row, _ = await get_owned(s, m.Population, population_id, user_id, "Population")
    groups = [ps.PopulationGroup.model_validate(g) for g in row.groups]
    if region is not None:
        groups = [g for g in groups if g.region.country_code == region]
    if interest is not None:
        groups = [g for g in groups if any(interest in (i.ref_id, i.name) for i in g.interests)]
    return _pa().landscape_view(groups, is_demo=row.mode == "demo", limit=limit)


async def reaction_map(user_id: UUID, population_study_id: UUID, element: str | None, group_id: str | None,
                       limit: int) -> ps.GraphView:
    async with read_session() as s:
        row, _ = await _owned_study(s, user_id, population_study_id)
        run = await s.get(m.AgentRun, row.id)
        population = await s.get(m.Population, row.population_id) if row.population_id else None
        interviews = await _interviews(s, row.id, *([m.Interview.group_id == group_id] if group_id else []))
        version = await s.get(m.CampaignVersion, row.content_version_id)
    groups = [ps.PopulationGroup.model_validate(g) for g in (population.groups if population else [])]
    if group_id is not None:
        groups = [g for g in groups if g.id == group_id]
    content = CampaignContent.model_validate(version.content) if version else None
    view = _pa().reaction_map_view(groups, interviews, content, is_demo=bool(run and run.mode == "demo"),
                                recommendations=(row.result or {}).get("next_actions", []), limit=limit)
    if element is None:
        return view
    hidden = {n.id for n in view.nodes if n.kind == "campaign_element" and n.id != f"element:{element}"}
    return view.model_copy(update={
        "nodes": [n for n in view.nodes if n.id not in hidden],
        "edges": [e for e in view.edges if e.source not in hidden and e.target not in hidden],
        "limitations": view.limitations + [f"Filtered to the campaign element {element}."]})


async def comparison(user_id: UUID, campaign_id: UUID, population_id: UUID, study_ids: list[UUID]) -> ps.CampaignComparison:
    async with read_session() as s:
        campaign, _ = await get_owned(s, m.Campaign, campaign_id, user_id, "Campaign")
        population, _ = await get_owned(s, m.Population, population_id, user_id, "Population", "population_id")
        summaries, results, depths, mode, numbers = [], [], set(), "live", {}
        for index, study_id in enumerate(study_ids):
            field = f"population_study_ids.{index}"
            row, project = await get_owned(s, m.PopulationStudy, study_id, user_id, "Population study", field)
            if row.campaign_id != campaign.id:
                raise conflict(field, "The population study belongs to another campaign.")
            summary = await _study_summary(s, row)
            summary.pop("_run")
            summaries.append(ps.PopulationStudySummary.model_validate(summary))
            version = await s.get(m.CampaignVersion, row.content_version_id)
            numbers[row.id] = version.version_number if version else None
            depths.add(row.interview_depth)
            mode = project.mode
            # The tally needs only group, status, and reaction; skipping the answer payloads keeps this fast.
            tallies = (await s.execute(select(m.Interview.group_id, m.Interview.status, m.Interview.reaction).where(
                m.Interview.run_id == row.id))).all()
            for group in population.groups:
                mine = [t for t in tallies if t.group_id == group["id"]]
                results.append(ps.VersionGroupResult(content_version_id=row.content_version_id, population_study_id=row.id,
                                                     group_id=group["id"], distribution=_pa().distribution(mine)))
    same_population = all(x.population_id == population.id for x in summaries)
    # One node per study: two studies of the same content version are still separate measurements.
    nodes = [ps.ViewNode(id=f"study:{x.id}", kind="campaign_version", label=f"Version {numbers[x.id]} · study {i + 1}",
                         group_id=None, region=None, size=float(x.completed_interviews),
                         facts={"content_version_id": str(x.content_version_id), "version_number": numbers[x.id]},
                         resource="population_study", resource_id=str(x.id), is_synthetic=False, is_demo=mode == "demo")
             for i, x in enumerate(summaries)]
    nodes += [ps.ViewNode(id=f"group:{g['id']}", kind="audience_group", label=g["label"], group_id=g["id"],
                          region=g["region"]["country_code"], size=float(g.get("participant_count", 0)), facts={},
                          resource="population", resource_id=str(population.id), is_synthetic=True, is_demo=mode == "demo")
              for g in population.groups]
    edges = [ps.ViewEdge(id=f"cmp:{r.population_study_id}:{r.group_id}", source=f"study:{r.population_study_id}",
                         target=f"group:{r.group_id}", relation="compared_on", weight=r.distribution.rates.get("positive"),
                         weight_definition="Share of the group's completed interviews with a positive reaction.",
                         provenance="interviews.reaction tallied per population study and group")
             for r in results]
    legend = [ps.LegendItem(kind="campaign_version", label="Campaign version",
                            description="One population study of a content version (size = completed interviews)."),
              ps.LegendItem(kind="audience_group", label="Audience group", description="Synthetic archetype.")]
    graph = ps.GraphView(view="campaign_comparison", nodes=nodes, edges=edges, legend=legend, truncated=False,
                         limitations=[] if same_population else ["The studies did not all use this population."],
                         generated_at=utcnow())
    return ps.CampaignComparison(
        campaign_id=campaign.id, population_id=population.id, studies=summaries, results=results,
        consistent_population=same_population, consistent_protocol=len(depths) == 1,
        variability_note="Repeated model sampling varies; differences are not tested for significance.",
        graph=graph, limitations=([] if len(depths) == 1 else ["The studies used different interview depths."]),
    )


async def diffusion(user_id: UUID, simulation_id: UUID, round_index: int | None, limit: int) -> ps.GraphView:
    async with read_session() as s:
        row, _ = await get_owned(s, m.SocialSimulation, simulation_id, user_id, "Social simulation")
        run = await s.get(m.AgentRun, row.id)
        study = await s.get(m.PopulationStudy, row.population_study_id)
        population = await s.get(m.Population, study.population_id) if study and study.population_id else None
        rounds = row.checkpoint.get("completed_rounds", [])
        chosen = round_index or (max(rounds) if rounds else 1)
        # Feeds cite earlier rounds' posts and peers' interviews, so load both to resolve every influence edge.
        posts = await _posts(s, row.id, m.SocialPost.round_index <= chosen)
        interview_groups = {interview_id: group_id for interview_id, group_id in (await s.execute(
            select(m.Interview.id, m.Interview.group_id).where(m.Interview.run_id == row.population_study_id))).all()}
    groups = [ps.PopulationGroup.model_validate(g) for g in (population.groups if population else [])]
    return _pa().diffusion_view(groups, posts, chosen, is_demo=bool(run and run.mode == "demo"), limit=limit,
                                interview_groups=interview_groups)


