async def participant_detail(user_id: UUID, population_study_id: UUID, participant_id: UUID) -> ps.ParticipantDetail:
    async with read_session() as s:
        row, participant, _ = await _participant_in_study(s, user_id, population_study_id, participant_id)
        interview = (await s.execute(select(m.Interview).where(m.Interview.run_id == row.id,
                                                              m.Interview.participant_id == participant.id))).scalar_one_or_none()
        sims = [x.id for x in (await s.execute(select(m.SocialSimulation).where(
            m.SocialSimulation.population_study_id == row.id))).scalars()]
        own = list((await s.execute(select(m.SocialPost).where(m.SocialPost.simulation_id.in_(sims),
                                                                m.SocialPost.participant_id == participant.id))).scalars()) if sims else []
        seen_ids = {UUID(str(i)) for p in own for i in p.seen_post_ids}
        seen = list((await s.execute(select(m.SocialPost).where(m.SocialPost.id.in_(seen_ids)))).scalars()) if seen_ids else []
        follow_ups = list((await s.execute(select(m.FollowUp).where(m.FollowUp.population_study_id == row.id,
                                                                     m.FollowUp.participant_id == participant.id))).scalars())
    memories: list[ps.MemoryItem] = []
    if interview is not None:
        record = to_interview(interview)
        first = next((a.answer for a in record.answers if a.question_id == "first_impression"), None)
        memories.append(ps.MemoryItem(kind="interview", ref_id=interview.id, round_index=None, created_at=interview.created_at,
                                      summary=(first or f"Interview ({record.status})")[:300]))
    memories += [ps.MemoryItem(kind="own_post", ref_id=p.id, round_index=p.round_index, created_at=p.created_at,
                               summary=(p.text or f"{p.action} ({p.stance})")[:300]) for p in own]
    memories += [ps.MemoryItem(kind="seen_post", ref_id=p.id, round_index=p.round_index, created_at=p.created_at,
                               summary=(p.text or f"{p.action} ({p.stance})")[:300]) for p in seen]
    memories += [ps.MemoryItem(kind="follow_up", ref_id=f.id, round_index=None, created_at=f.created_at,
                               summary=f"Q: {f.question[:120]} A: {f.answer[:170]}") for f in follow_ups]
    memories.sort(key=lambda x: (x.created_at, x.round_index or 0), reverse=True)
    latest_post = max(own, key=lambda p: (p.round_index, p.created_at), default=None)
    if latest_post is not None:
        state = ps.ParticipantState(population_study_id=row.id, stance=latest_post.stance, stance_source="social_round",  # type: ignore[arg-type]
                                    last_round_index=latest_post.round_index, interview_id=interview.id if interview else None)
    elif interview is not None:
        state = ps.ParticipantState(population_study_id=row.id, stance=interview.reaction, stance_source="interview",  # type: ignore[arg-type]
                                    last_round_index=None, interview_id=interview.id)
    else:
        state = ps.ParticipantState(population_study_id=row.id, stance=None, stance_source="none", last_round_index=None,
                                    interview_id=None)
    return ps.ParticipantDetail.model_validate(to_participant(participant).model_dump() | {
        "state": state, "memories": memories[:50]})


def _to_follow_up(row: m.FollowUp) -> ps.FollowUpAnswer:
    return ps.FollowUpAnswer(id=row.id, population_study_id=row.population_study_id, participant_id=row.participant_id,
                             group_id=row.group_id, question=row.question, answer=row.answer, stance=row.stance,  # type: ignore[arg-type]
                             memory_refs=row.memory_refs, model_id=row.model_id, created_at=row.created_at)


def _known_refs(refs: Any, detail: ps.ParticipantDetail) -> list[str]:
    """Model output is untrusted: keep only memory refs that are this participant's stored memories."""
    known = {str(item.ref_id) for item in detail.memories}
    return [ref for ref in dict.fromkeys(str(r) for r in refs) if ref in known]


def _answerer(name: str) -> Any:
    from app import workflows

    function = getattr(workflows, name, None)
    if function is None:
        raise UnsupportedCapability("Asking participants questions is not configured on this server.")
    return function


async def _answer(function: Any, **kwargs: Any) -> Any:
    """One synchronous model call; a typed LLMError becomes its contract error code, never a 500."""
    from app.llm.gateway import LLMError

    try:
        return await function(**kwargs)
    except LLMError as exc:
        error = AppError(exc.message)
        error.code = exc.code
        error.status_code = {"PROVIDER_TIMEOUT": 504, "RATE_LIMITED": 429, "PROVIDER_NOT_CONFIGURED": 503}.get(exc.code, 502)
        raise error from exc


async def ask_participant(user_id: UUID, population_study_id: UUID, participant_id: UUID,
                          body: ps.FollowUpCreate) -> ps.FollowUpAnswer:
    detail = await participant_detail(user_id, population_study_id, participant_id)  # 404 before anything else
    async with read_session() as s:
        row, participant, project = await _participant_in_study(s, user_id, population_study_id, participant_id)
        require_writable(project)
    answer = await _answer(_answerer("answer_followup"), population_study_id=row.id, participant=detail,
                           question=body.question, mode=project.mode)
    record = m.FollowUp(id=uuid4(), project_id=project.id, population_study_id=row.id, participant_id=participant.id,
                        group_id=participant.group_id, group_question_id=None, question=body.question,
                        answer=answer.answer, stance=answer.stance, memory_refs=_known_refs(answer.memory_refs, detail),
                        model_id=answer.model_id, created_at=utcnow())
    async with session() as s, s.begin():
        s.add(record)
    return _to_follow_up(record)


