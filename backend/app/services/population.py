async def get_social_simulation(user_id: UUID, simulation_id: UUID) -> ps.SocialSimulationResult:
    async with read_session() as s:
        row, _ = await get_owned(s, m.SocialSimulation, simulation_id, user_id, "Social simulation")
        summary, run = await _simulation_summary(s, row)
        study = await s.get(m.PopulationStudy, row.population_study_id)
        assert study is not None and study.population_id is not None
        population = await s.get(m.Population, study.population_id)
        assert population is not None
        participants = await _participants(s, population.id)
        interviews = await _interviews(s, study.id)
    groups = [ps.PopulationGroup.model_validate(g) for g in population.groups]
    before = {i.participant_id: i.reaction for i in interviews}
    after = {UUID(k): v for k, v in row.checkpoint.get("stances", {}).items()} or before
    stored = row.result or {}
    network = stored.get("network") or ps.NetworkDefinition(method="Not built yet: the simulation has not finished.",
                                                             degree=0, similarity_definition="n/a")
    return ps.SocialSimulationResult.model_validate(summary | {
        "network": network, "rounds": row.checkpoint.get("rounds", []),
        "group_shifts": _pa().group_shifts(groups, participants, before, after), "emergent_themes": [],
        "influence_paths": stored.get("influence_paths", []), "disclosure": SOCIAL_DISCLOSURE,
        "limitations": stored.get("limitations", [] if row.result else ["The simulation has not finished, or it "
                                                                        "stopped early; rounds shown are the stored ones."]),
        "run_metadata": run_metadata(run),
    })


