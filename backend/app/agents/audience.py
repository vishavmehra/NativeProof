"""Audience agent: model-generated segment assumptions (when the study has none) and synthetic reactions.

Every reaction is AI-generated and labeled synthetic; it is never a real participant (docs/03 A3).
"""

import random
from dataclasses import dataclass
from functools import lru_cache
from typing import Annotated, ClassVar, Literal
from uuid import uuid4

from pydantic import Field, create_model

from app.agents._common import EVIDENCE_RULES, Strict, content_dict, pick, untrusted
from app.analytics import DEFINITIONS
from app.llm.gateway import LLMGateway
from app.schemas.campaigns import CampaignContent
from app.schemas.common import Dimension, Market, RiskFlag, RiskSeverity, StepTrace
from app.schemas.evidence import EvidenceRecord
from app.schemas.studies import DimensionRating, Sentiment, SyntheticReaction

SEGMENTS_PROMPT_VERSION = "audience-segments-v1"
REACTIONS_PROMPT_VERSION = "audience-reactions-v1"
MAX_REACTIONS_PER_CALL = 8
# Seeded per-reaction reading contexts vary perspectives by explicit design, not random demographics (docs/05 §12.4).
READING_CONTEXTS = (
    "scrolling past it quickly on a phone",
    "reading it closely while considering a purchase",
    "skeptical of advertising claims",
    "seeing it shared by a friend",
    "comparing it with a competitor's advertisement",
    "seeing it on a transit poster during a commute",
)
ModelRiskCategory = Literal["stereotype", "sensitivity", "ambiguity", "brand_inconsistency", "unsupported_claim", "other"]


class SegmentOut(Strict):
    label: str = Field(min_length=1, max_length=60)
    description: str = Field(min_length=1, max_length=300)


class _SegmentsBase(Strict):
    schema_version: ClassVar[str] = "segment-assumptions-v1"


@lru_cache
def segments_schema(count: int) -> type[_SegmentsBase]:
    return create_model(
        "SegmentAssumptionsOut", __base__=_SegmentsBase,
        segments=(Annotated[list[SegmentOut], Field(min_length=count, max_length=count)], ...),
    )


SEGMENTS_SYSTEM = """You design audience segments for a synthetic campaign rehearsal in Nativeproof.
Each segment is an explicit hypothesis about a group of potential customers in the market, described by attitudes,
needs, and context relevant to the campaign. Never use sensitive traits (ethnicity, religion, health, sexuality,
politics) and never claim a segment is measured or representative. Labels are short; descriptions are one sentence."""


class RatingOut(Strict):
    value: int = Field(ge=1, le=5)
    rationale: str | None = Field(default=None, max_length=300)


class ReactionRiskOut(Strict):
    severity: RiskSeverity
    category: ModelRiskCategory
    description: str = Field(max_length=300)


class _ReactionBase(Strict):
    interpretation: str = Field(max_length=500, description="What this person takes the message to mean.")
    reaction_summary: str = Field(max_length=500)
    sentiment: Sentiment
    confusion_level: float = Field(ge=0, le=1, description="0 = fully understood, 1 = not understood.")
    potential_confusions: list[str] = Field(default=[], max_length=4)
    risk_flags: list[ReactionRiskOut] = Field(default=[], max_length=3)
    relevant_passage: str | None = Field(default=None, max_length=300, description="Exact quote from the campaign, or null.")
    evidence: list[str] = Field(default=[], max_length=4)


class _ReactionsBase(Strict):
    schema_version: ClassVar[str] = "synthetic-reaction-v1"


@lru_cache
def reactions_schema(dimensions: tuple[Dimension, ...], count: int) -> type[_ReactionsBase]:
    ratings = create_model("RatingsOut", __base__=Strict, **{d: (RatingOut, ...) for d in dimensions})
    reaction = create_model("ReactionOut", __base__=_ReactionBase, ratings=(ratings, ...))
    return create_model(
        "SyntheticReactionsOut", __base__=_ReactionsBase,
        reactions=(Annotated[list[reaction], Field(min_length=1, max_length=count)], ...),
    )


REACTIONS_SYSTEM = f"""You simulate how one described audience segment might read a campaign, for Nativeproof's
synthetic rehearsal. Each reaction is generated by an AI model and is never a real person: do not claim otherwise and
do not invent statistics or quotes from real people. Stay within the segment's stated assumptions and write one
reaction per assigned reading context, in order. Reactions may disagree; do not force consensus.
Rate every listed dimension with an integer 1-5; for cultural_risk, 5 means the most perceived risk.
relevant_passage must quote the campaign text exactly, or be null. Cite evidence handles only when a record informed the reaction.
{EVIDENCE_RULES}"""


@dataclass
class SegmentDraft:
    label: str
    assumptions: str
    source: Literal["user", "model"]


async def generate_segments(
    llm: LLMGateway, *, stage: str, count: int, market: Market, content: CampaignContent, brand: dict | str,
    research_questions: list[str], seed: int | None,
) -> tuple[list[SegmentDraft], StepTrace]:
    payload = {"count": count, "market": market.model_dump()}
    user = "\n\n".join([
        f"Design exactly {count} distinct audience segments for {market.display_name} ({market.country_code}).",
        untrusted("research_questions", research_questions),
        brand if isinstance(brand, str) else untrusted("brand", brand),
        untrusted("campaign_content", content_dict(content)),
    ])
    result = await llm.generate_structured(
        task="study_design", stage=stage, agent="audience", system=SEGMENTS_SYSTEM, user=user,
        schema=segments_schema(count), prompt_version=SEGMENTS_PROMPT_VERSION, temperature=0.5, seed=seed,
        fixture_context=payload,
    )
    drafts, seen = [], set()
    for s in result.value.segments:
        if s.label.casefold() not in seen:  # labels key the segment summaries, so they must be unique
            seen.add(s.label.casefold())
            drafts.append(SegmentDraft(s.label, s.description, "model"))
    return drafts, result.trace


def reading_contexts(seed: int | None, segment_index: int, count: int, offset: int = 0) -> list[str]:
    start = random.Random(f"{seed}:{segment_index}").randrange(len(READING_CONTEXTS))
    return [READING_CONTEXTS[(start + offset + k) % len(READING_CONTEXTS)] for k in range(count)]


async def generate_reactions(
    llm: LLMGateway, *, stage: str, segment: SegmentDraft, segment_index: int, count: int, offset: int,
    dimensions: list[Dimension], market: Market, content: CampaignContent, brand: dict | str, research_questions: list[str],
    evidence: list[dict], handles: dict[str, EvidenceRecord], seed: int | None,
    prompt_version: str = REACTIONS_PROMPT_VERSION, observations: list[str] | None = None,
) -> tuple[list[SyntheticReaction], StepTrace, int]:
    """Returns (reactions, trace, dropped evidence handles). The model may return fewer than `count`."""
    contexts = reading_contexts(seed, segment_index, count, offset)
    payload = {
        "segment_index": segment_index, "segment_label": segment.label, "count": count, "offset": offset,
        "dimensions": list(dimensions), "content": content_dict(content), "evidence": evidence,
    }
    criteria = "\n".join(f"- {d}: {DEFINITIONS[d][1]}" for d in dimensions)
    user = "\n\n".join([
        f"Market: {market.display_name} ({market.country_code}).",
        f"Segment ({'user-provided' if segment.source == 'user' else 'model-generated'} assumption): {segment.label}.",
        untrusted("segment_assumptions", segment.assumptions),
        f"Write {count} reactions, one per reading context, in this order: " + "; ".join(contexts) + ".",
        f"Rate each dimension 1-5:\n{criteria}",
        untrusted("research_questions", research_questions),
        brand if isinstance(brand, str) else untrusted("brand", brand),
        untrusted("campaign_content", content_dict(content)),
        *([untrusted("visual_observations", observations)] if observations else []),
        untrusted("evidence", evidence),
    ])
    result = await llm.generate_structured(
        task="synthetic_generation", stage=stage, agent="audience", system=REACTIONS_SYSTEM, user=user,
        schema=reactions_schema(tuple(dimensions), count), prompt_version=prompt_version, temperature=0.8,
        seed=seed, fixture_context=payload,
    )
    copy = " ".join(p for p in (content.headline, content.body, content.call_to_action) if p).casefold()
    reactions, dropped = [], 0
    for item in result.value.reactions[:count]:
        cited, lost = pick(item.evidence, handles)
        dropped += lost
        passage = item.relevant_passage if item.relevant_passage and item.relevant_passage.casefold() in copy else None
        reactions.append(
            SyntheticReaction(
                id=uuid4(), segment_label=segment.label, interpretation=item.interpretation,
                reaction_summary=item.reaction_summary, sentiment=item.sentiment,
                ratings=[
                    DimensionRating(dimension=d, value=getattr(item.ratings, d).value, rationale=getattr(item.ratings, d).rationale)
                    for d in dimensions
                ],
                confusion_level=item.confusion_level, potential_confusions=item.potential_confusions,
                risk_flags=[RiskFlag(**f.model_dump(), source="model_assessment") for f in item.risk_flags],
                relevant_passage=passage, evidence_ids=[e.id for e in cited],
            )
        )
    return reactions, result.trace, dropped
